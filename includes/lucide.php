/**
 * Returns an inline Lucide SVG icon.
 * $opts: size (int, default 16), class (string), color (string, default 'currentColor'),
 * stroke_width (float, default 2), title (string, for aria-label).
 */
function lucide(string $name, array $opts = []): string
{
    if (!isset(LUCIDE_ICONS[$name])) return '';

    $size   = $opts['size'] ?? 16;
    $class  = $opts['class'] ?? '';
    $stroke = $opts['stroke_width'] ?? 2;
    $title  = $opts['title'] ?? '';

    $attrs = 'xmlns="http://www.w3.org/2000/svg" width="' . (int)$size . '" height="' . (int)$size .
        '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="' . htmlspecialchars((string)$stroke) .
        '" stroke-linecap="round" stroke-linejoin="round"';

    if ($class) $attrs .= ' class="lucide-icon ' . htmlspecialchars($class) . '"';
    if ($title) $attrs .= ' role="img" aria-label="' . htmlspecialchars($title) . '"';
    else $attrs .= ' aria-hidden="true" focusable="false"';

    return '<svg ' . $attrs . ' style="display:inline-block;vertical-align:middle;flex-shrink:0">' . LUCIDE_ICONS[$name] . '</svg>';
}

/** Icon + label badge for a bounty's type (replaces the old emoji version of bountyTypeBadge()). */
function bountyTypeIconKey(array $bounty): string
{
    switch ($bounty['type']) {
        case 'official': return 'crown';
        case 'external': return 'link';
        case 'hosted':
        default:
            return !empty($bounty['host_is_verified']) ? 'shield-check' : 'users';
    }
}

/** Maps a bounty category slug to a Lucide icon key (categories keep their emoji in the DB for backward compatibility, but the UI renders this instead). */
function bountyCategoryIconKey(?string $slug): string
{
    return [
        'development' => 'zap',
        'design'      => 'sparkles',
        'content'     => 'file-text',
        'research'    => 'search',
        'community'   => 'users',
        'other'       => 'briefcase',
    ][$slug] ?? 'briefcase';
}
